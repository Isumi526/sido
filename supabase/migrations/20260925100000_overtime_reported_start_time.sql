--  20260925100000_overtime_reported_start_time.sql
--  残業申請の取りこぼしをなくす・早出版（A-1 の範囲追加・2026-09-25）。追加のみ。
--
--  ★何が起きていたか（2026-09-25 今井さん「予定作業時間より早く出て仕事する場合残業申請でできますか？」の調査）:
--   早出は残業申請の「早朝入りの開始時刻」で申請できるが、日報で固定開始より前を選べるのは**承認済みの日だけ**。
--   さらに締切前の通常申請は、承認されても提出済みの日報の開始時刻を書き戻さない。
--   「朝7時に入る→昼に申請→夜に日報(定時開始でしか出せない)→翌朝承認」だと早出の分がどこにも残らない。
--   終了時刻（20260924100000 reported_end_time）と同じ構造。
--
--  ★扱いは終了時刻と同じ（運用者決定 2026-09-25）:
--   申請が pending の日は固定開始より前を**入力できる**。日報に保存するのは固定開始から（承認まで金額は動かない）で、
--   入力された時刻はこの列に置き、承認されたらこの時刻で日報を書き換える。
--   締切前の通常申請でこの列が空なら、承認しても開始時刻は触らない（requested_start_time で代用すると過払いになる）。
-- ============================================================
alter table public.overtime_requests
  add column if not exists reported_start_time time null;

comment on column public.overtime_requests.reported_start_time is
  '承認待ちの間に日報で入力された開始時刻（現場の固定開始より前＝早出の分）。承認時にこの時刻で日報を書き換える。requested_start_time（事前申告）とは別に持つ';
