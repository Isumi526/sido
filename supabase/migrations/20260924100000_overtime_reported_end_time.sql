-- ============================================================
--  20260924100000_overtime_reported_end_time.sql
--  残業申請の取りこぼしをなくす（A-1・2026-09-24）。追加のみ。
--
--  ★何が起きていたか（2026-09-23 お客様報告・本番実測）:
--   日報の終了時刻は現場の固定終了までしか選べず、上限が外れるのは「承認済み」の日だけだった。
--   締切前申請の36%（14件中5件）は翌日以降に承認されており、その日のうちに日報を出す作業員は
--   残業時刻を選べないまま提出＝「残業申請してない形」で送られていた。
--
--  ★新しい扱い（運用者確認済み）:
--   申請が pending の日は、定時を超える終了時刻を日報に**入力できる**。ただし
--   日報に保存するのは定時まで（集計・人件費は承認まで動かない）で、入力された時刻は
--   この列に記録する。承認されたら、この時刻で日報を書き換える。
--
--  ★requested_end_time と分ける理由:
--   requested_end_time は「16:00 締切までに事前に申告した時刻」＝架空残業対策の証跡。
--   日報（夕方）から上書きすると、14時に出した申請が夜に黙って書き換わり、
--   管理者が承認時に見ていた数字と払う数字がずれる。
--   承認画面では両方を並べ、管理者は「実際に払う時刻（この列）」を見て承認する。
--
--  ★締切前の通常申請でこの列が空なら、承認しても日報の終了時刻は触らない。
--   requested_end_time で代用すると「19:30で申請→実際は18:00で上がり日報も18:00」の人に
--   19:30 が書き込まれて過払いになるため。
-- ============================================================
alter table public.overtime_requests
  add column if not exists reported_end_time time null;

comment on column public.overtime_requests.reported_end_time is
  '承認待ちの間に日報で入力された終了時刻（現場の固定終了を超えた分）。承認時にこの時刻で日報を書き換える。requested_end_time（事前申告）とは別に持つ';
