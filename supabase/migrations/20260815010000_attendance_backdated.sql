-- ============================================================
--  20260815010000_attendance_backdated.sql
--  打刻を忘れた日を、あとから遡って入力できるようにする
--  Notion: 打刻を忘れた日でも、あとから遡って打刻できるようにする（3〜4日前まで）
--
--  出所: 大塚さんとの電話 2026-08-10
--   「次の日でも別に今までと同じような感じで、4日前まできればいいんじゃない？3日前か」
--   「出勤するのを忘れたとしても…18時だとしても、出勤するよってすぐ〔打刻〕して、
--     実際に時間を打ち込む」
--
--  ★なぜ既存行の書き換えではなく「追記」なのか（巻き戻し禁止）:
--   attendance_logs は UPDATE / DELETE を RLS で全面禁止している（20260529000000）。
--   打刻は「あとから直せない記録」であることが存在意義で、同意したルール文面の
--   スナップショットも法的証拠として持っている。遡り入力を UPDATE で実装すると
--   その前提が崩れるので、遡り分も1件の新しいログとして INSERT する。
--
--  ★なぜ created_at との差で判定しないのか:
--   checked_at と created_at の差で「遡り入力」を推定はできるが、端末の時計ずれや
--   通信の遅れで数分ずれた普通の打刻まで遡り扱いになりうる。
--   「本人がその場で押した」のか「あとから思い出して入れた」のかは意味が違うので、
--   推定せず明示的に持つ。
--
--  追加のみDDL（ADD COLUMN）。既存列・既存データに変更なし。
-- ============================================================

alter table attendance_logs
  add column if not exists backdated boolean not null default false;

comment on column attendance_logs.backdated is
  'true = 打刻し忘れた日をあとから入力した記録（その場で押した打刻ではない）。'
  ' 管理画面で区別して見せるために使う。既存行はすべて false（その場で押した打刻）。';

