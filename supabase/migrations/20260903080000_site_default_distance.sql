-- ============================================================
--  20260903080000_site_default_distance.sql
--  現場ごとに「会社から現場までの距離(km)」を登録し、日報で既定値として
--  自動入力できるようにする（第1段: 登録・既定値の反映まで）
--
--  出所: 2026-09-02 要望「現場住所を入れたら距離を自動計算」→ 実測の結果、
--   165現場中6件しか住所が入っておらず会社住所を保存する場所も無いため、
--   住所→自動計算ではなく「現場ごとに距離を1回登録→日報で既定値」に決定
--   （2026-09-03 ユーザー判断）。
--
--  ★方針（ユーザー確定）:
--   1. 現場ごとに距離をAで登録 → 日報で既定値として自動入力
--   2. 手動で編集も可能
--   3. 手動値が既定値より大きい場合は理由の入力＋現場管理者の承認を必須にする
--   4. 承認が下りるまでは既定値で計上し、承認後に申請値へ差し替える
--
--  ★このmigrationは1（登録・既定値）までのスコープ。3の承認フローは
--   expense-flatten（経費データの消費箇所が10箇所以上ある領域・
--   docs/expense-data-consumers.md）に触れるため、既定値の反映が
--   きちんと動くことを先に固めてから別migrationで追加する。
--
--  ★追加のみ。既存の列・データ・挙動は触らない。
-- ============================================================

alter table public.sites
  add column if not exists default_distance_km numeric(6,1);

comment on column public.sites.default_distance_km is
  '会社からこの現場までの往復距離(km)の既定値。日報のガソリン代（距離按分）の'
  ' 初期値として使う。手動編集は可能（既定値より大きい場合は理由＋承認が必要＝別途実装）。';
