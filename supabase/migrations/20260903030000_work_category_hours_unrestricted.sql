-- ============================================================
--  20260903030000_work_category_hours_unrestricted.sql
--  作業区分ごとに「時刻の制限をかけない」を選べるようにする
--
--  ★なぜ必要か（2026-09-03 運用者判断・案D）:
--   日報の時刻ピッカーは定時の外（早出＝固定開始より前／残業＝固定終了より後）を
--   選択肢から外している。「早出・残業は承認制」という意図的なガード。
--   ただし見積・事務のように定時という概念が合わない区分では、これが邪魔になる。
--
--   実際、本番(sido)では見積・その他事務に 05:00〜22:00 という広い定時が
--   入れられていた＝ガードを避けるための回避策。定時のふりをした無制限で、
--   画面からは意図が読めない。これを正式な設定にする。
--
--  ★残業代への影響は無い。
--   残業は「実働8時間超」で決まる（worker-hours の OT = 480）。定時とは無関係。
--   定時が効いているのは「フォームの初期値」と「選べる範囲の制限」だけ。
--
--  ★追加のみ。既定は false ＝ これまでどおり制限あり。
--   既存データ（05:00〜22:00 等）はそのままでも挙動は変わらない。
-- ============================================================

alter table public.work_categories
  add column if not exists hours_unrestricted boolean not null default false;

comment on column public.work_categories.hours_unrestricted is
  '日報の時刻ピッカーで定時の外も選べるようにするか。true=制限なし（見積・事務など）。'
  ' false（既定）=定時の範囲のみ＝早出/残業は承認制のまま。'
  ' ★定時(default_start_time/end_time)はフォームの初期値としては引き続き使う。';
